// Checks every piece the way Herdr would meet it.
//
//   1. every JSON file parses; nothing Herdr generates is committed
//   2. a layout names only mods its piece brings (or Herdr ships), its node ids
//      are unique, it shows no machine's own terminals, its theme and preview exist
//   3. every "mods/<name>/<file>" a built mod names exists, and is in its own piece
//   4. `herdr-app check` loads and renders every mod once, in a throwaway home
//
//   node scripts/check.ts     (herdr-app on PATH: `ocx exec -- task check`)

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { ROOT, mods, pieces, rel, walk } from "./repo.ts";

const GENERATED = new Set(["gpui-kit.d.ts", "jsconfig.json"]);
// Mods every Herdr install has; a layout may name them without bringing them.
const SHIPPED = new Set(["agents", "changes", "confirm", "files", "help", "machine-add", "menu", "new-menu", "pane", "peek", "picker", "prompt", "spaces", "tabs", "toast", "workspace-chrome", "workspace-status", "worktree"]);
const BUILTIN_THEMES = new Set(["graphite", "ink", "moss", "paper", "atom-one-dark"]);

interface LayoutNode {
  id?: string;
  content?: { mod?: string; terminal?: string; pane?: { header?: { content?: { mod?: string } } } };
  header?: unknown;
  children?: LayoutNode[];
  floating?: LayoutNode[];
  [key: string]: unknown;
}

const problems: string[] = [];
const warnings: string[] = [];
const fail = (where: string, what: string) => problems.push(`${where}: ${what}`);

const allPieces = pieces();
const allMods = mods();
if (!allPieces.length) fail("repository", "no piece found (a folder with mods/ in it)");
const pieceOf = new Map<string, string>();
for (const mod of allMods) {
  if (pieceOf.has(mod.name)) fail(rel(mod.folder), `also in ${pieceOf.get(mod.name)}: a mod name must be unique in the repository`);
  pieceOf.set(mod.name, mod.piece);
}

// 1. JSON, generated files, what a piece needs to be shared
for (const piece of allPieces) {
  for (const file of walk(path.join(ROOT, piece))) {
    if (GENERATED.has(path.basename(file))) fail(rel(file), "generated by Herdr, must not be committed");
    if (!file.endsWith(".json")) continue;
    const text = fs.readFileSync(file, "utf8");
    if (text.charCodeAt(0) === 0xfeff) fail(rel(file), "starts with a BOM, Herdr rejects it");
    try { JSON.parse(text.replace(/^﻿/, "")); } catch (error) { fail(rel(file), `invalid JSON: ${(error as Error).message}`); }
  }
  if (!fs.existsSync(path.join(ROOT, piece, "RECIPE.md"))) fail(piece, "no RECIPE.md");
  if (!fs.existsSync(path.join(ROOT, piece, "preview.png"))) warnings.push(`${piece}: no preview.png yet (herdr.dev needs one to list it)`);
}

// 2. layouts
for (const piece of allPieces) {
  const dir = path.join(ROOT, piece, "layouts");
  if (!fs.existsSync(dir)) continue;
  for (const name of fs.readdirSync(dir).filter((file) => file.endsWith(".json"))) {
    const where = `${piece}/layouts/${name}`;
    let tree: LayoutNode;
    try { tree = JSON.parse(fs.readFileSync(path.join(dir, name), "utf8")); } catch { continue; }
    const ids = new Set<string>();
    const named = new Set<string>();
    const visit = (node: LayoutNode) => {
      if (node.id) {
        if (ids.has(node.id)) fail(where, `node id "${node.id}" is used twice`);
        ids.add(node.id);
      }
      const header = typeof node.header === "object" ? (node.header as { mod?: string } | null)?.mod : undefined;
      for (const mod of [node.content?.mod, node.content?.pane?.header?.content?.mod, header]) if (mod) named.add(mod);
      if (node.content?.terminal) fail(where, `node "${node.id}" shows terminal ${node.content.terminal}: that is one machine's terminal, not a layout`);
      for (const child of [...(node.children ?? []), ...(node.floating ?? [])]) visit(child);
    };
    visit(tree);
    for (const key of ["terminal_menu", "toast"]) if (typeof tree[key] === "string") named.add(tree[key] as string);
    for (const mod of named) {
      if (pieceOf.get(mod) !== piece && !SHIPPED.has(mod)) fail(where, `names mod "${mod}", which is neither in ${piece}/mods nor shipped with Herdr`);
    }
    const theme = tree.theme as string | Record<string, string> | undefined;
    for (const one of typeof theme === "string" ? [theme] : Object.values(theme ?? {})) {
      if (!BUILTIN_THEMES.has(one) && !fs.existsSync(path.join(ROOT, piece, "themes", `${one}.json`))) fail(where, `theme "${one}" is not in ${piece}/themes`);
    }
    if (typeof tree.preview !== "string") fail(where, 'no preview picture (root "preview")');
    else if (!fs.existsSync(path.join(ROOT, piece, tree.preview))) fail(where, `preview ${tree.preview} is missing`);
    if (tree.cloned_from) fail(where, "still carries cloned_from");
  }
}

// 3. the files a built mod names
for (const mod of allMods) {
  if (!fs.existsSync(mod.built)) { fail(rel(mod.folder), "no main.js: run `task build`"); continue; }
  if (!fs.existsSync(path.join(mod.folder, "mod.json"))) fail(rel(mod.folder), "no mod.json");
  for (const [, name, asset] of fs.readFileSync(mod.built, "utf8").matchAll(/["'`]mods\/([A-Za-z0-9_-]+)\/([A-Za-z0-9_.\/-]+\.[a-z0-9]+)["'`]/g)) {
    const home = pieceOf.get(name);
    if (!home) continue; // a shipped mod's file
    if (home !== mod.piece) fail(rel(mod.built), `names mods/${name}/${asset} from another piece (${home}): a piece must stand alone`);
    else if (!fs.existsSync(path.join(ROOT, home, "mods", name, asset))) fail(rel(mod.built), `names mods/${name}/${asset}, which does not exist`);
  }
}

// 4. herdr-app check, in a home that holds every piece
const version = spawnSync("herdr-app", ["--version"], { encoding: "utf8" });
if (version.status !== 0) fail("herdr-app", "not on PATH: run through `ocx exec -- task check`");
else {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), "herdr-check-"));
  for (const piece of allPieces) {
    fs.cpSync(path.join(ROOT, piece), home, { recursive: true, filter: (source) => !/(RECIPE\.md|preview\.png)$/.test(source) });
  }
  console.log(version.stdout.trim());
  for (const mod of allMods) {
    const result = spawnSync("herdr-app", ["check", path.join(home, "mods", mod.name)], { env: { ...process.env, HERDR_APP_HOME: home }, encoding: "utf8", timeout: 120000 });
    if (result.status === 0) console.log(`ok    ${rel(mod.folder)}`);
    else fail(rel(mod.folder), `herdr-app check failed${result.error ? ` (${result.error.message})` : ""}:\n${`${result.stdout ?? ""}${result.stderr ?? ""}`.trim()}`);
  }
  fs.rmSync(home, { recursive: true, force: true });
}

const ci = Boolean(process.env.GITHUB_ACTIONS);
for (const warning of warnings) console.log(ci ? `::warning::${warning}` : `warn  ${warning}`);
if (problems.length) {
  for (const problem of problems) console.error(ci ? `::error::${problem.replaceAll("\n", "%0A")}` : `FAIL  ${problem}`);
  process.exit(1);
}
console.log(`${allPieces.length} pieces, ${allMods.length} mods: all checks passed`);
