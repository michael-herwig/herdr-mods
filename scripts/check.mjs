// Checks every piece in this repository the way Herdr would meet it.
//
// A piece is a top-level folder laid out like the Herdr app's home
// (mods/, and for a layout also layouts/ and themes/). The checks:
//   1. every JSON file parses; nothing the app generates is committed
//   2. a layout names only mods the piece brings (or Herdr ships), its node
//      ids are unique, its theme and preview exist
//   3. every "mods/<name>/<file>" a mod names exists, when <name> is in this repo
//   4. `herdr-app check` loads and renders every mod once, in a throwaway home
//   5. the mods written here from scratch (TYPED) pass `tsc` against the
//      declarations of the pinned Herdr version
//
// Run: node scripts/check.mjs            (herdr-app and node on PATH: `ocx pull`)
//      node scripts/check.mjs --no-types  skips step 5

import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const GENERATED = new Set(["gpui-kit.d.ts", "jsconfig.json"]);
// Mods every Herdr install has; a layout may name them without bringing them.
const SHIPPED = new Set(["agents", "changes", "confirm", "files", "help", "machine-add", "menu", "new-menu", "pane", "peek", "picker", "prompt", "spaces", "tabs", "toast", "workspace-chrome", "workspace-status", "worktree"]);
const BUILTIN_THEMES = new Set(["graphite", "ink", "moss", "paper", "atom-one-dark"]);
// Written here, not cloned from Herdr's: these are held to the type check.
const TYPED = ["term-panel", "voxel-neon"];
const TYPESCRIPT = "typescript@5.6.3";

const problems = [];
const warnings = [];
const fail = (where, what) => problems.push(`${where}: ${what}`);
const rel = (p) => path.relative(ROOT, p).replaceAll("\\", "/");

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

const pieces = fs.readdirSync(ROOT, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(ROOT, d.name, "mods")))
  .map((d) => d.name);
if (!pieces.length) fail("repository", "no piece found (a folder with mods/ in it)");

const modHome = {}; // mod name -> the piece that brings it
for (const piece of pieces) {
  for (const mod of fs.readdirSync(path.join(ROOT, piece, "mods"))) {
    if (modHome[mod]) fail(`${piece}/mods/${mod}`, `also in ${modHome[mod]}: a mod name must be unique in the repository`);
    modHome[mod] = piece;
  }
}

// 1. JSON and generated files
for (const piece of pieces) {
  for (const file of walk(path.join(ROOT, piece))) {
    if (GENERATED.has(path.basename(file))) fail(rel(file), "generated by Herdr, must not be committed");
    if (file.endsWith(".json")) {
      const text = fs.readFileSync(file, "utf8");
      if (text.charCodeAt(0) === 0xfeff) fail(rel(file), "starts with a BOM, Herdr rejects it");
      try { JSON.parse(text.replace(/^﻿/, "")); } catch (error) { fail(rel(file), `invalid JSON: ${error.message}`); }
    }
  }
  if (!fs.existsSync(path.join(ROOT, piece, "RECIPE.md"))) fail(piece, "no RECIPE.md");
  if (!fs.existsSync(path.join(ROOT, piece, "preview.png"))) warnings.push(`${piece}: no preview.png yet (herdr.dev needs one to list it)`);
}

// 2. layouts
for (const piece of pieces) {
  const dir = path.join(ROOT, piece, "layouts");
  if (!fs.existsSync(dir)) continue;
  for (const name of fs.readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    const where = `${piece}/layouts/${name}`;
    let tree;
    try { tree = JSON.parse(fs.readFileSync(path.join(dir, name), "utf8")); } catch { continue; }
    const ids = new Set();
    const mods = new Set();
    const visit = (node) => {
      if (node.id) { if (ids.has(node.id)) fail(where, `node id "${node.id}" is used twice`); ids.add(node.id); }
      for (const mod of [node.content?.mod, node.content?.pane?.header?.content?.mod, typeof node.header === "object" ? node.header?.mod : null]) if (mod) mods.add(mod);
      if (node.content?.terminal) fail(where, `node "${node.id}" shows terminal ${node.content.terminal}: that is one machine's terminal, not a layout`);
      for (const child of [...(node.children ?? []), ...(node.floating ?? [])]) visit(child);
    };
    visit(tree);
    for (const key of ["terminal_menu", "toast"]) if (tree[key]) mods.add(tree[key]);
    for (const mod of mods) {
      if (modHome[mod] !== piece && !SHIPPED.has(mod)) fail(where, `names mod "${mod}", which is neither in ${piece}/mods nor shipped with Herdr`);
    }
    const themes = typeof tree.theme === "string" ? [tree.theme] : Object.values(tree.theme ?? {});
    for (const theme of themes) {
      if (!BUILTIN_THEMES.has(theme) && !fs.existsSync(path.join(ROOT, piece, "themes", `${theme}.json`))) fail(where, `theme "${theme}" is not in ${piece}/themes`);
    }
    if (!tree.preview) fail(where, "no preview picture (root \"preview\")");
    else if (!fs.existsSync(path.join(ROOT, piece, tree.preview))) fail(where, `preview ${tree.preview} is missing`);
    if (tree.cloned_from) fail(where, "still carries cloned_from");
  }
}

// 3. assets named in mod code
for (const [mod, piece] of Object.entries(modHome)) {
  const dir = path.join(ROOT, piece, "mods", mod);
  if (!fs.existsSync(path.join(dir, "main.js"))) { fail(`${piece}/mods/${mod}`, "no main.js"); continue; }
  for (const file of walk(dir).filter((f) => f.endsWith(".js"))) {
    for (const [, name, asset] of fs.readFileSync(file, "utf8").matchAll(/["'`]mods\/([A-Za-z0-9_-]+)\/([A-Za-z0-9_.\/-]+\.[a-z0-9]+)["'`]/g)) {
      const home = modHome[name];
      if (home && !fs.existsSync(path.join(ROOT, home, "mods", name, asset))) fail(rel(file), `names mods/${name}/${asset}, which does not exist`);
      if (home && home !== piece) fail(rel(file), `names mods/${name}/${asset} from another piece (${home}): a piece must stand alone`);
    }
  }
}

// 4. herdr-app check, in a home that holds every piece
const home = fs.mkdtempSync(path.join(os.tmpdir(), "herdr-check-"));
for (const piece of pieces) fs.cpSync(path.join(ROOT, piece), home, { recursive: true, filter: (src) => !/(RECIPE\.md|preview\.png)$/.test(src) });
const env = { ...process.env, HERDR_APP_HOME: home };
let version = "not found";
try { version = execFileSync("herdr-app", ["--version"], { encoding: "utf8" }).trim(); } catch { fail("herdr-app", "not on PATH (run `ocx pull`, or `ocx exec -- node scripts/check.mjs`)"); }
console.log(`${version}, home ${home}`);
if (version !== "not found") {
  for (const [mod, piece] of Object.entries(modHome).sort()) {
    const result = spawnSync("herdr-app", ["check", path.join(home, "mods", mod)], { env, encoding: "utf8", timeout: 120000 });
    const output = `${result.stdout ?? ""}${result.stderr ?? ""}`.trim();
    if (result.status === 0) console.log(`ok    ${piece}/mods/${mod}`);
    else fail(`${piece}/mods/${mod}`, `herdr-app check failed${result.error ? ` (${result.error.message})` : ""}:\n${output}`);
  }
}

// 5. types, for the mods written here
if (!process.argv.includes("--no-types") && version !== "not found") {
  const typed = TYPED.filter((mod) => modHome[mod]);
  const declarations = typed.map((mod) => path.join(home, "mods", mod, "gpui-kit.d.ts")).find((f) => fs.existsSync(f));
  if (!declarations) fail("types", "herdr-app check wrote no gpui-kit.d.ts to check against");
  else {
    fs.writeFileSync(path.join(home, "tsconfig.json"), JSON.stringify({
      compilerOptions: {
        target: "ES2022", module: "ES2022", moduleResolution: "bundler", lib: ["ES2022"],
        allowJs: true, checkJs: true, noEmit: true, skipLibCheck: true,
        // As Herdr's own jsconfig.json: strict, without null checks (a view sets its state in init).
        strict: true, strictNullChecks: false,
        // Parameters go unannotated in mods; what is checked is every call into gpui-kit and herdr.
        noImplicitAny: false, useUnknownInCatchVariables: false,
        paths: { herdr: [path.join(ROOT, "types", "herdr.d.ts")] },
      },
      files: [declarations, ...typed.map((mod) => path.join(home, "mods", mod, "main.js"))],
    }, null, 2));
    // npx is a .cmd on Windows, which only a shell can start.
    const tsc = ["-y", "-p", TYPESCRIPT, "tsc", "-p", path.join(home, "tsconfig.json")];
    const result = process.platform === "win32"
      ? spawnSync(`npx ${tsc.map((arg) => `"${arg}"`).join(" ")}`, { encoding: "utf8", shell: true, timeout: 300000 })
      : spawnSync("npx", tsc, { encoding: "utf8", timeout: 300000 });
    const output = `${result.stdout ?? ""}${result.stderr ?? ""}`.trim().replaceAll(home, "<home>");
    if (result.status === 0) console.log(`ok    types: ${typed.join(", ")}`);
    else fail("types", `tsc failed${result.error ? ` (${result.error.message})` : ""}:\n${output}`);
  }
}

fs.rmSync(home, { recursive: true, force: true });
for (const warning of warnings) console.log(process.env.GITHUB_ACTIONS ? `::warning::${warning}` : `warn  ${warning}`);
if (problems.length) {
  for (const problem of problems) console.error(process.env.GITHUB_ACTIONS ? `::error::${problem.replaceAll("\n", "%0A")}` : `FAIL  ${problem}`);
  process.exit(1);
}
console.log(`\n${pieces.length} pieces, ${Object.keys(modHome).length} mods: all checks passed`);
